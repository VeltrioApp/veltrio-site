let currentLang = "fr";
let currentSlide = "tvos-home";
const resolvedDownloads = {};

function applyLanguage(lang) {
  currentLang = lang;
  document.documentElement.lang = lang;
  const dict = I18N[lang];
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key]) el.innerHTML = dict[key];
  });
  document.querySelectorAll(".lang-toggle button").forEach((btn) => {
    btn.classList.toggle("active", btn.dataset.lang === lang);
  });
  renderSlide(currentSlide);
  updateHeroCTA();
}

function renderSlide(id) {
  currentSlide = id;
  const slide = SLIDES[id];
  const frame = document.getElementById("showcase-frame");
  const cap = document.getElementById("showcase-caption-text");

  document.querySelectorAll(".showcase-tab").forEach((tab) => {
    tab.classList.toggle("active", tab.dataset.slide === id);
  });

  if (slide.type === "phone-duo") {
    frame.className = "showcase-frame phone-duo";
    frame.innerHTML = slide.srcs
      .map(
        (src, i) =>
          `<div class="phone-bezel"><img src="${src}" alt="${slide.alts[i]}" /></div>`
      )
      .join("");
  } else if (slide.type === "ipad") {
    frame.className = "showcase-frame ipad-stage";
    frame.innerHTML = `<div class="ipad-bezel"><img src="${slide.src}" alt="${slide.alt}" /></div>`;
  } else {
    frame.className = "showcase-frame";
    frame.innerHTML = `<img src="${slide.src}" alt="${slide.alt}" />`;
  }

  cap.textContent = I18N[currentLang][slide.capKey];
}

function detectPlatform() {
  const ua = navigator.userAgent || "";
  if (/Android/i.test(ua)) return { repo: "veltrio-android", label: "Android" };
  if (/Windows/i.test(ua)) return { repo: "veltrio-windows", label: "Windows" };
  if (/Macintosh|Mac OS X/i.test(ua) && !("ontouchend" in document)) return { repo: "veltrio-macos", label: "macOS" };
  return null;
}

function updateHeroCTA() {
  const cta = document.getElementById("hero-primary-cta");
  if (!cta) return;
  const plat = detectPlatform();
  if (!plat) return;
  const card = document.querySelector(`.dl-card[data-repo="${plat.repo}"]`);
  const info = resolvedDownloads[plat.repo];
  const fallbackHref = card?.querySelector("[data-dl-link]")?.getAttribute("href");
  const ver = info?.version || card?.querySelector("[data-dl-version]")?.textContent || "";
  const href = info?.url || fallbackHref;
  if (href && href.startsWith("http")) {
    cta.href = href;
    cta.textContent = currentLang === "fr"
      ? `Télécharger pour ${plat.label}${ver ? ` · ${ver}` : ""}`
      : `Download for ${plat.label}${ver ? ` · ${ver}` : ""}`;
  }
}

// Resolve direct download links from the latest GitHub release for each platform.
async function hydrateDownloadLinks() {
  const cards = document.querySelectorAll(".dl-card[data-repo]");
  await Promise.all(
    Array.from(cards).map(async (card) => {
      const repo = card.dataset.repo;
      const ext = card.dataset.ext;
      const link = card.querySelector("[data-dl-link]");
      const ver = card.querySelector("[data-dl-version]");
      try {
        const res = await fetch(`https://api.github.com/repos/VeltrioApp/${repo}/releases/latest`);
        if (!res.ok) return;
        const rel = await res.json();
        if (!rel || !rel.tag_name) return;
        if (ver) {
          ver.textContent = rel.tag_name;
          ver.classList.remove("muted");
          ver.removeAttribute("data-i18n");
        }
        const asset = (rel.assets || []).find((a) => a.name.endsWith(ext));
        const url = asset ? asset.browser_download_url : rel.html_url;
        if (url && link) {
          link.href = url;
          resolvedDownloads[repo] = { url, version: rel.tag_name };
        }
      } catch {
        // Keep hardcoded latest direct links
      }
    })
  );
  updateHeroCTA();
}

// Smooth scroll reveal
const observer = new IntersectionObserver(
  (entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("visible");
        observer.unobserve(entry.target);
      }
    });
  },
  { threshold: 0.12 }
);
document.querySelectorAll(".reveal").forEach((el) => observer.observe(el));

document.querySelectorAll(".lang-toggle button").forEach((btn) => {
  btn.addEventListener("click", () => applyLanguage(btn.dataset.lang));
});

document.querySelectorAll(".showcase-tab").forEach((tab) => {
  tab.addEventListener("click", () => renderSlide(tab.dataset.slide));
});

renderSlide(currentSlide);
updateHeroCTA();
hydrateDownloadLinks();
