const SLIDES = {
  "tvos-home":        { mode: "full", src: "assets/tvos-home.jpg", alt: "Veltrio Apple TV", cap: "cap.tvhome" },
  "ios-duo":          { mode: "duo",  srcs: ["assets/ios-home.jpg", "assets/ios-detail.jpg"], alts: ["Veltrio iPhone", "Veltrio Detail"], cap: "cap.iphone" },
  "ipad-home":        { mode: "ipad", src: "assets/ipad-home.jpg", alt: "Veltrio iPad", cap: "cap.ipad" },
  "tvos-player":      { mode: "full", src: "assets/tvos-player.jpg", alt: "Veltrio Player", cap: "cap.player" },
  "androidtv-player": { mode: "full", src: "assets/androidtv-player.jpg", alt: "Veltrio Android TV", cap: "cap.androidtv" }
};

let lang = "fr";
let slide = "tvos-player";
const resolved = {};

function setLang(l) {
  lang = l;
  document.documentElement.lang = l;
  const d = I18N[l];
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const k = el.getAttribute("data-i18n");
    if (d[k]) el.textContent = d[k];
  });
  document.querySelectorAll(".lang-switch button").forEach((b) => b.classList.toggle("active", b.dataset.lang === l));
  setSlide(slide);
  updateHeroCTA();
}

function setSlide(id) {
  slide = id;
  const s = SLIDES[id];
  const box = document.getElementById("shot-box");
  const cap = document.getElementById("shot-caption");
  document.querySelectorAll(".shot-tab").forEach((t) => t.classList.toggle("active", t.dataset.slide === id));
  if (s.mode === "duo") {
    box.className = "shot-box duo";
    box.innerHTML = s.srcs.map((src, i) => `<img src="${src}" alt="${s.alts[i]}" />`).join("");
  } else if (s.mode === "ipad") {
    box.className = "shot-box ipad";
    box.innerHTML = `<img src="${s.src}" alt="${s.alt}" />`;
  } else {
    box.className = "shot-box";
    box.innerHTML = `<img src="${s.src}" alt="${s.alt}" />`;
  }
  cap.textContent = I18N[lang][s.cap];
}

function detectOS() {
  const ua = navigator.userAgent || "";
  if (/Android/i.test(ua)) return { repo: "veltrio-android", label: "Android" };
  if (/Windows/i.test(ua)) return { repo: "veltrio-windows", label: "Windows" };
  if (/Macintosh|Mac OS X/i.test(ua) && !("ontouchend" in document)) return { repo: "veltrio-macos", label: "macOS" };
  return null;
}

function updateHeroCTA() {
  const cta = document.getElementById("hero-cta");
  const os = detectOS();
  if (!cta || !os) return;
  const row = document.querySelector(`.dl-item[data-repo="${os.repo}"]`);
  const info = resolved[os.repo];
  const href = info?.url || row?.querySelector("[data-dl-link]")?.getAttribute("href");
  const ver = info?.version || row?.querySelector("[data-dl-version]")?.textContent || "";
  if (href && href.startsWith("http")) {
    cta.href = href;
    cta.textContent = lang === "fr"
      ? `Télécharger pour ${os.label}${ver ? ` (${ver})` : ""}`
      : `Download for ${os.label}${ver ? ` (${ver})` : ""}`;
  }
}

async function hydrate() {
  const items = document.querySelectorAll(".dl-item[data-repo]");
  await Promise.all(Array.from(items).map(async (item) => {
    const repo = item.dataset.repo;
    const ext = item.dataset.ext;
    const link = item.querySelector("[data-dl-link]");
    const ver = item.querySelector("[data-dl-version]");
    try {
      const r = await fetch(`https://api.github.com/repos/VeltrioApp/${repo}/releases/latest`);
      if (!r.ok) return;
      const rel = await r.json();
      if (!rel?.tag_name) return;
      if (ver) {
        ver.textContent = rel.tag_name;
        ver.classList.remove("muted");
        ver.removeAttribute("data-i18n");
      }
      const asset = (rel.assets || []).find((a) => a.name.endsWith(ext));
      const url = asset ? asset.browser_download_url : rel.html_url;
      if (url && link) {
        link.href = url;
        resolved[repo] = { url, version: rel.tag_name };
      }
    } catch { /* fallback to hardcoded links */ }
  }));
  updateHeroCTA();
}

document.querySelectorAll(".lang-switch button").forEach((b) => b.addEventListener("click", () => setLang(b.dataset.lang)));
document.querySelectorAll(".shot-tab").forEach((t) => t.addEventListener("click", () => setSlide(t.dataset.slide)));

const copyAlt = document.getElementById("copy-altstore");
if (copyAlt) {
  copyAlt.addEventListener("click", async () => {
    try {
      await navigator.clipboard.writeText("https://veltrioapp.com/altstore.json");
      copyAlt.textContent = I18N[lang]["dl.altstore.copied"];
      setTimeout(() => { copyAlt.textContent = I18N[lang]["dl.altstore.copy"]; }, 2200);
    } catch {
      window.prompt("AltStore Classic source URL:", "https://veltrioapp.com/altstore.json");
    }
  });
}

setSlide(slide);
updateHeroCTA();
hydrate();
